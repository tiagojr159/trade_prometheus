CREATE TABLE IF NOT EXISTS paper_trading_heartbeat (
  mode ENUM('DIRECTIONAL','STRATEGY') NOT NULL PRIMARY KEY,
  status ENUM('ACTIVE','STOPPED','ERROR') NOT NULL DEFAULT 'STOPPED',
  last_started_at DATETIME NULL,
  last_finished_at DATETIME NULL,
  last_prediction_id BIGINT UNSIGNED NULL,
  last_decision VARCHAR(24) NULL,
  last_reason TEXT NULL,
  last_error TEXT NULL,
  next_evaluation_at DATETIME NULL,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB;

